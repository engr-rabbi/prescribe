// Bundles the shared backend core + Google adapters into ONE Apps Script file.
//   npm run build:gas   →   apps-script/dist/Code.js  +  appsscript.json
import { build } from "esbuild";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
mkdirSync(path.join(root, "apps-script/dist"), { recursive: true });

const result = await build({
  entryPoints: [path.join(root, "apps-script/src/entry.ts")],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "__RX",
  platform: "neutral",
  target: "es2016", // lowers async/await → generators (driven by the sync Promise polyfill)
  tsconfig: path.join(root, "tsconfig.json"),
  alias: { "@": path.join(root, "src") },
  define: {
    "process.env.NEXT_PUBLIC_BASE_PATH": '""',
    "process.env.NODE_ENV": '"production"',
  },
  minify: false,
  legalComments: "none",
  logLevel: "info",
});

const code = result.outputFiles[0].text;
const exportsList = ["doGet", "doPost", "setup", "dailyBackup", "clearCaches", "selfTest", "resetAdminPassword"];
const shims = exportsList.map((n) => `function ${n}(e) { return __RX.${n}(e); }`).join("\n");
const banner = "// Generated by `npm run build:gas` — do not edit by hand. Source: apps-script/src + src/lib/local-backend\n";
writeFileSync(path.join(root, "apps-script/dist/Code.js"), `${banner}${code}\n${shims}\n`);
copyFileSync(path.join(root, "apps-script/appsscript.json"), path.join(root, "apps-script/dist/appsscript.json"));
console.log(`apps-script/dist/Code.js  ${(readFileSync(path.join(root, "apps-script/dist/Code.js")).length / 1024).toFixed(0)} KB`);
